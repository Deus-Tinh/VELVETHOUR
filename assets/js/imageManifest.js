export function getImageById(id) {
  const found = IMAGE_MANIFEST.find(item => item.id === id);
  return found || {
    url: 'assets/images/hero_1.webp',
    altText: 'Serenity Spa & Retreat'
  };
}

const PACKAGE_IMAGE_URL = /^\/api\/package-images\/[0-9a-f-]{36}$/i;
const THERAPY_IMAGE_URL = /^\/api\/therapy-images\/[0-9a-f-]{36}$/i;
const LEGACY_SEED_IMAGE_IDS = Object.freeze({
  'foot-back-neck': { from: 'foot-01', to: 'back-massage-01' },
  'deo-dai-nhe-chan': { from: 'foot-01', to: 'thai-stretch-01' },
  'moc-tam-duong-sinh': { from: 'hair-01', to: 'pkg-moc-tam-01' },
  'lam-moi-tha-long': { from: 'body-01', to: 'pkg-lam-moi-01' },
  'am-da-sang-da': { from: 'massage-02', to: 'pkg-am-da-01' },
  'goi-thao-moc-cham-da': { from: 'facial-01', to: 'pkg-goi-thao-moc-01' },
});

export function getServiceImage(service) {
  const legacyImage = LEGACY_SEED_IMAGE_IDS[service?.id];
  const legacyImageId = legacyImage?.from === service?.imageId ? legacyImage.to : null;
  const fallback = getImageById(legacyImageId || service?.imageId);
  const isPackage = service?.kind === 'package' || service?.category === 'packages';
  const validImageUrl = typeof service?.imageUrl === 'string'
    && (isPackage ? PACKAGE_IMAGE_URL.test(service.imageUrl) : THERAPY_IMAGE_URL.test(service.imageUrl));
  return validImageUrl
    ? { ...fallback, url: service.imageUrl }
    : fallback;
}
